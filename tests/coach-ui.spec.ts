import { test, expect, type Page } from "@playwright/test";
import { mkdir } from "node:fs/promises";
import { localDateInTimeZone, shiftLocalDate } from "../lib/timezone";
test.use({ trace: "off" });
test("Coach calendar persists daily selections and onboarding lives in Add Client across devices", async ({ page, browser }, info) => {
  test.skip(process.env.RAVOGE_COACH_UI_QA !== "yes" || process.env.SUPABASE_DB_TARGET !== "local" || info.project.name !== "desktop", "Isolated local fixtures only");
  test.setTimeout(180000);
  const users = JSON.parse(process.env.BETA_QA_USERS!) as { email: string; password: string; role: string }[];
  const owner = users.find(u => u.role === "owner")!;
  const coach = users.find(u => u.role === "coach")!;
  const client = users.find(u => u.role === "client")!;
  async function login(p: Page, u: typeof coach) {
    await p.goto("/login");
    await p.getByLabel("Email", { exact: true }).fill(u.email);
    await p.getByLabel("Password", { exact: true }).fill(u.password);
    await p.getByRole("button", { name: "Login", exact: true }).click();
    await expect(p).toHaveURL(new RegExp(`/${u.role}$`));
  }
  await login(page, owner);
  await page.goto("/owner/apps");
  await expect(page.locator('[data-enrollment-card="client"] [data-qr-value]')).toBeVisible();
  await page.locator('a[aria-label="Ravoge home"]:visible').first().click();
  await expect(page).toHaveURL(/\/owner$/);
  await page.getByRole("button", { name: "Log out", exact: true }).click();
  await login(page, coach);
  const today = localDateInTimeZone(new Date(), "UTC");
  const date = shiftLocalDate(today, 1)!;
  const target = new Date(`${date}T12:00:00Z`).getUTCDay() === 0 ? shiftLocalDate(date, 1)! : date;
  await mkdir("test-results", { recursive: true });
  for (const width of [390, 820, 1440]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.goto("/coach");
    await expect(page.getByRole("heading", { name: "Today’s schedule", exact: true })).toBeVisible();
    await expect(page.locator("[data-qr-value]")).toHaveCount(0);
    await expect(page.getByRole("heading", { name: "Invite a client", exact: true })).toHaveCount(0);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: `test-results/coach-ui-dashboard-${width}.png`, fullPage: true });
    await page.goto(`/coach/availability?date=${target}`);
    await expect(page.getByRole("region", { name: "Monthly availability calendar" })).toBeVisible();
    await expect(page.locator('input[type="time"],input[type="datetime-local"]')).toHaveCount(0);
    await page.getByRole("button", { name: "45 minutes", exact: true }).click();
    const slot = page.getByRole("button", { name: /5:00 AM – 5:45 AM/ });
    const selected = await slot.getAttribute("aria-pressed");
    await slot.click();
    await expect(slot).toHaveAttribute("aria-pressed", selected === "true" ? "false" : "true");
    await page.getByRole("button", { name: "Save Availability", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("Availability saved.");
    await page.reload();
    await expect(page.getByRole("button", { name: "45 minutes", exact: true })).toHaveAttribute("aria-pressed", "true");
    await expect(slot).toHaveAttribute("aria-pressed", selected === "true" ? "false" : "true");
    await page.getByRole("button", { name: "60 minutes", exact: true }).focus();
    await page.keyboard.press("Enter");
    await expect(page.getByRole("button", { name: "60 minutes", exact: true })).toHaveAttribute("aria-pressed", "true");
    await page.getByRole("button", { name: "Save Availability", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("Availability saved.");
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    const bounds = await slot.count() ? await slot.boundingBox() : await page.getByRole("button", { name: /5:00 AM – 6:00 AM/ }).boundingBox();
    expect(bounds!.height).toBeGreaterThanOrEqual(44);
    await page.screenshot({ path: `test-results/coach-ui-availability-${width}.png`, fullPage: true });
    await page.getByRole("navigation", { name: "coach navigation" }).getByRole("link", { name: "Add Client", exact: true }).click();
    await expect(page).toHaveURL(/\/coach\/add-client$/);
    await expect(page.getByRole("heading", { name: "Add Client", exact: true })).toBeVisible();
    await expect(page.locator('[data-client-signup-tools] [data-qr-value]')).toHaveAttribute("data-qr-value", /\/enroll\/client\?token=/);
    await expect(page.getByRole("button", { name: "Copy signup link", exact: true })).toBeVisible();
    await expect(page.getByRole("button", { name: "Share signup link", exact: true })).toBeVisible();
    await expect(page.getByRole("heading", { name: "Invite a client", exact: true })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: `test-results/coach-ui-add-client-${width}.png`, fullPage: true });
    const logo = page.locator('a[aria-label="Ravoge home"]:visible').first();
    await expect(logo).toHaveAttribute("href", "/coach");
    await expect(logo.locator("img")).toBeVisible();
    expect(await logo.locator("img").evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth > 0)).toBe(true);
    await logo.focus(); await page.keyboard.press("Enter");
    await expect(page).toHaveURL(/\/coach$/);
  }
  await page.goto("/coach/add-client");
  const recipient = process.env.BETA_QA_NEW_CLIENT_EMAIL!;
  await page.getByLabel("Email", { exact: true }).fill(recipient);
  await page.getByRole("button", { name: "Send invite", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Invitation history", exact: true })).toBeVisible();
  await expect(page.locator("li").filter({ hasText: recipient })).toContainText("pending");
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Revoke", exact: true }).click();
  await expect(page.locator("li").filter({ hasText: recipient })).toContainText("revoked");
  await page.goto("/home"); await expect(page).toHaveURL(/\/coach$/);
  const context = await browser.newContext();
  const p = await context.newPage();
  await login(p, client);
  await p.goto("/home"); await expect(p).toHaveURL(/\/client$/);
  await p.locator('a[aria-label="Ravoge home"]:visible').first().click();
  await expect(p).toHaveURL(/\/client$/);
  await p.goto("/coach/add-client"); await expect(p).toHaveURL(/\/client$/);
  await context.close();
});
